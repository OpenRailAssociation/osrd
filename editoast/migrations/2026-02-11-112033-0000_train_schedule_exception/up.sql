CREATE TABLE IF NOT EXISTS train_schedule_exception (
	id int8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    key TEXT,
	occurrence_index int8,
    disabled BOOLEAN NOT NULL DEFAULT FALSE,
	change_groups JSONB NOT NULL,
	timetable_id int8 NOT NULL REFERENCES timetable(id) ON DELETE CASCADE,
	train_schedule_id int8 NOT NULL REFERENCES train_schedule(id) ON DELETE CASCADE,
    UNIQUE (timetable_id, train_schedule_id, occurrence_index)
);

ALTER TABLE train_schedule_exception
ADD CONSTRAINT idx_unique_train_schedule_by_key
UNIQUE (timetable_id, train_schedule_id, key);

CREATE INDEX IF NOT EXISTS idx_timetable_id_train_schedule_exception
    ON train_schedule_exception(timetable_id);

CREATE INDEX IF NOT EXISTS idx_train_schedule_id_train_schedule_exception
    ON train_schedule_exception(train_schedule_id);
