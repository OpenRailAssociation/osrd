CREATE TABLE search_journey_environment (
    id int8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    infra_id int8 NOT NULL REFERENCES infra(id) -- No CASCADE
);

CREATE TABLE search_journey_environment_timetable (
    id int8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    search_journey_environment_id int8 NOT NULL REFERENCES search_journey_environment(id) ON DELETE CASCADE,
    timetable_id int8 NOT NULL REFERENCES timetable(id), -- No CASCADE
    UNIQUE(search_journey_environment_id, timetable_id)
);

-- No index because those tables should have very few rows

CREATE OR REPLACE FUNCTION check_search_journey_environment_timetable_type_is_calendar()
    RETURNS TRIGGER
    LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM timetable
        WHERE timetable.id = NEW.timetable_id
            AND timetable.timetable_type != 'CALENDAR'
    )
    THEN
        RAISE EXCEPTION 'Cannot insert or update search_journey_environment_timetable with non calendar timetable_type in timetable';
    END IF;
    RETURN NEW;
END;
$$;
CREATE OR REPLACE TRIGGER trigger_check_search_journey_environment_timetable_type_is_calendar
BEFORE INSERT OR UPDATE OF timetable_id ON search_journey_environment_timetable
FOR EACH ROW EXECUTE FUNCTION check_search_journey_environment_timetable_type_is_calendar();
