-- A timetable includes the timetables of its train schedule sets
CREATE TABLE timetable_inheritance (
    id int8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    -- The timetable containing another timetable
    outer_timetable_id int8 NOT NULL REFERENCES timetable(id) ON DELETE CASCADE,
    -- The timetable included in another timetable
    inner_timetable_id int8 NOT NULL REFERENCES timetable(id) ON DELETE CASCADE,
    ranges JSONB,
    UNIQUE (outer_timetable_id, inner_timetable_id),
    CHECK (outer_timetable_id <> inner_timetable_id)
);
CREATE INDEX idx_timetable_inheritance_inner_timetable_id ON timetable_inheritance (inner_timetable_id);

INSERT INTO timetable_inheritance (outer_timetable_id, inner_timetable_id)
SELECT timetable_train_schedule_set.timetable_id, train_schedule_set.timetable_id
FROM timetable_train_schedule_set
INNER JOIN train_schedule_set ON train_schedule_set.id = timetable_train_schedule_set.train_schedule_set_id;

CREATE OR REPLACE FUNCTION check_timetable_inheritance()
    RETURNS TRIGGER
    LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM timetable
        WHERE id = NEW.outer_timetable_id
            AND is_train_schedule_set
    ) THEN
        RAISE EXCEPTION 'Invalid timetable_inheritance: a train schedule set cannot include a timetable';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM timetable AS outer_timetable, timetable AS inner_timetable
        WHERE outer_timetable.id = NEW.outer_timetable_id
            AND inner_timetable.id = NEW.inner_timetable_id
            AND inner_timetable.is_train_schedule_set
            AND inner_timetable.timetable_type = outer_timetable.timetable_type
            AND NEW.ranges IS NULL
    ) THEN
        RAISE EXCEPTION 'Invalid timetable_inheritance: only a train schedule set of the same type can be included and ranges must be NULL';
    END IF;

    RETURN NEW;
END;
$$;
CREATE OR REPLACE TRIGGER trigger_check_timetable_inheritance
BEFORE INSERT OR UPDATE OF outer_timetable_id, inner_timetable_id, ranges ON timetable_inheritance
FOR EACH ROW EXECUTE FUNCTION check_timetable_inheritance();

-- Drops along its trigger, constraints and indexes
DROP TABLE timetable_train_schedule_set;
DROP FUNCTION check_timetable_and_train_schedule_set_same_type;
