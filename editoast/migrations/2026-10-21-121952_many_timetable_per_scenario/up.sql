-- This migration shifts from a 1-1 relation between timetable and scenario to n-m
-- This will allow to have many timetables per scenario
CREATE TABLE scenario_timetable (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, -- we need this column due to our model macro
    scenario_id bigint REFERENCES scenario(id) ON DELETE CASCADE NOT NULL,
    timetable_id bigint REFERENCES timetable(id) ON DELETE CASCADE NOT NULL,
    UNIQUE(scenario_id, timetable_id)
);

-- The UNIQUE constraint will add an index, but it’s mostly effective on the most left value (scenario_id)
-- That is why we add an explicit index
-- https://www.postgresql.org/docs/current/indexes-multicolumn.html
CREATE INDEX pga_idx_fk_scenario_timetable_timetable_id ON scenario_timetable (timetable_id);

INSERT INTO scenario_timetable(scenario_id, timetable_id)
SELECT id, timetable_id FROM scenario
WHERE timetable_id IS NOT NULL;

ALTER TABLE scenario
DROP COLUMN timetable_id;
