CREATE TABLE timetable_train_schedule_set (
    id int8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    timetable_id int8 NOT NULL REFERENCES timetable(id) ON DELETE CASCADE,
    train_schedule_set_id int8 NOT NULL REFERENCES train_schedule_set(id) ON DELETE CASCADE,
    UNIQUE (timetable_id, train_schedule_set_id)
);
CREATE INDEX idx_timetable_train_schedule_set_train_schedule_set_id ON timetable_train_schedule_set (train_schedule_set_id);

INSERT INTO timetable_train_schedule_set (timetable_id, train_schedule_set_id)
SELECT timetable_inheritance.outer_timetable_id, train_schedule_set.id
FROM timetable_inheritance
INNER JOIN train_schedule_set ON train_schedule_set.timetable_id = timetable_inheritance.inner_timetable_id;

CREATE OR REPLACE FUNCTION check_timetable_and_train_schedule_set_same_type()
    RETURNS TRIGGER
    LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM timetable, train_schedule_set
        INNER JOIN timetable AS train_schedule_set_timetable
            ON train_schedule_set_timetable.id = train_schedule_set.timetable_id
        WHERE timetable.id = NEW.timetable_id
            AND train_schedule_set.id = NEW.train_schedule_set_id
            AND timetable.timetable_type != train_schedule_set_timetable.timetable_type
    )
    THEN
        RAISE EXCEPTION 'Cannot insert or update timetable_train_schedule_set with mismatched timetable and train_schedule_set types';
    END IF;
    RETURN NEW;
END;
$$;
CREATE OR REPLACE TRIGGER trigger_check_timetable_and_train_schedule_set_same_type
BEFORE INSERT OR UPDATE OF timetable_id, train_schedule_set_id ON timetable_train_schedule_set
FOR EACH ROW EXECUTE FUNCTION check_timetable_and_train_schedule_set_same_type();

DROP TABLE timetable_inheritance;
DROP FUNCTION check_timetable_inheritance;
